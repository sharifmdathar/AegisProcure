#!/usr/bin/env node
/**
 * Prepares browser-consumable Midnight artifacts under public/ and src/shims/generated:
 *
 *  - public/managed/{keys,zkir}        fetched by FetchZkConfigProvider
 *  - public/managed/wasm               raw binaries (reference/debug)
 *  - src/shims/generated/*-base64.mjs  base64-embedded WASM used by the sync
 *    browser shims — webpack's @webassemblyjs parser cannot handle these
 *    rustc binaries, so they must never go through a bundler .wasm import.
 *    Same technique the SDK itself uses for @midnight-ntwrk/zswap.
 *
 * Run automatically before `dev` and `build` (see package.json pre-scripts).
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const SRC = join(ROOT, "managed");
const DEST = join(ROOT, "public", "managed");

if (!existsSync(SRC)) {
  console.error("sync-zk-assets: managed/ not found — run `npm run compact:build` first.");
  process.exit(1);
}

for (const dir of ["keys", "zkir"]) {
  const srcDir = join(SRC, dir);
  if (!existsSync(srcDir)) continue;
  mkdirSync(join(DEST, dir), { recursive: true });
  cpSync(srcDir, join(DEST, dir), { recursive: true });
  const count = readdirSync(join(DEST, dir)).length;
  console.log(`sync-zk-assets: public/managed/${dir} (${count} files)`);
}

// Raw binaries for the async browser shim (ledger exceeds Chromium's 8 MB
// synchronous-compile cap, so it must be fetched + compiled async instead of
// embedded like the smaller onchain runtime).
const wasmDir = join(ROOT, "public", "managed", "wasm");
mkdirSync(wasmDir, { recursive: true });
const LEDGER_BIN = readdirSync(join(ROOT, "node_modules", "@midnight-ntwrk", "ledger-v8")).find(
  (f) => f.endsWith(".wasm")
);
cpSync(
  join(ROOT, "node_modules", "@midnight-ntwrk", "ledger-v8", LEDGER_BIN),
  join(wasmDir, LEDGER_BIN)
);
console.log(`sync-zk-assets: public/managed/wasm/${LEDGER_BIN}`);

// Onchain runtime is small enough to embed and instantiate synchronously in
// the browser shim (src/shims/onchain-runtime-v3.browser.mjs), which imports
// WASM_BASE64 from the generated module below. webpack's @webassemblyjs parser
// cannot handle this rustc binary, so we base64-embed it instead of importing
// the raw .wasm. Regenerated on every predev/prebuild so it tracks the
// installed package version.
const ONCHAIN_DIR = join(ROOT, "node_modules", "@midnight-ntwrk", "onchain-runtime-v3");
const ONCHAIN_BIN = readdirSync(ONCHAIN_DIR).find((f) => f.endsWith(".wasm"));
if (!ONCHAIN_BIN) {
  console.error("sync-zk-assets: no .wasm found in @midnight-ntwrk/onchain-runtime-v3");
  process.exit(1);
}
const generatedDir = join(ROOT, "src", "shims", "generated");
mkdirSync(generatedDir, { recursive: true });
const onchainBytes = readFileSync(join(ONCHAIN_DIR, ONCHAIN_BIN));
const onchainBase64 = onchainBytes.toString("base64");
const outFile = join(generatedDir, "onchain-runtime-wasm-base64.mjs");
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/sync-zk-assets.mjs — do not edit.\n` +
    `// Source: node_modules/@midnight-ntwrk/onchain-runtime-v3/${ONCHAIN_BIN}\n` +
    `export const WASM_BASE64 = "${onchainBase64}";\n`
);
console.log(
  `sync-zk-assets: src/shims/generated/onchain-runtime-wasm-base64.mjs (${(onchainBytes.length / 1024).toFixed(0)} KB from ${ONCHAIN_BIN})`
);

